"use client";

import { motion } from "framer-motion";
import { CheckCircle, ShieldCheck, RotateCcwClock } from "lucide-react";

interface ResultCardProps {
  score: number;
  onRestart: () => void;
}

function getResult(score: number) {
  if (score < 4) {
    return {
      title: "Lower range",
      description:
        "Your predicted wellness score falls within the lower range based on the information you provided.",
      color: "text-red-500",
      badge: "border-red-100 bg-red-50 text-red-700",
      dot: "bg-red-500",
      progress: "text-red-500",
      bar: "bg-red-500",
      suggestions: [
        "Maintain a regular sleep schedule and daily routine.",
        "Stay physically active and spend some time outdoors.",
        "Keep in touch with friends, family, or people you trust.",
        "Make time for activities that help you relax and recharge.",
        "If concerns persist or affect your daily life, consider speaking with a qualified professional.",
      ],
    };
  }

  if (score < 7) {
    return {
      title: "Moderate range",
      description:
        "Your predicted wellness score falls within the moderate range based on the information you provided.",
      color: "text-amber-500",
      badge: "border-amber-100 bg-amber-50 text-amber-700",
      dot: "bg-amber-500",
      progress: "text-amber-500",
      bar: "bg-amber-500",
      suggestions: [
        "Pay attention to changes in your mood, sleep, energy, or stress levels.",
        "Maintain consistent sleep, meals, and physical activity.",
        "Make time for hobbies, social connection, and relaxation.",
        "Identify major sources of stress and look for small ways to manage them.",
        "If concerns persist or begin affecting daily life, consider speaking with a qualified professional.",
      ],
    };
  }

  return {
    title: "Higher range",
    description:
      "Your predicted wellness score falls within the higher range based on the information you provided.",
    color: "text-emerald-500",
    badge: "border-emerald-100 bg-emerald-50 text-emerald-700",
    dot: "bg-emerald-500",
    progress: "text-emerald-500",
    bar: "bg-emerald-500",
    suggestions: [
      "Continue the habits and routines that support your wellbeing.",
      "Maintain regular physical activity, healthy sleep, and social connection.",
      "Keep making time for hobbies and activities you enjoy.",
      "Check in with yourself periodically, especially during stressful periods.",
      "Remember that a higher predicted score does not mean you are immune to future difficulties.",
    ],
  };
}

export default function ResultCard({ score, onRestart }: ResultCardProps) {
  const result = getResult(score);

  const percentage = Math.min(Math.max((score / 10) * 100, 0), 100);

  const circumference = 2 * Math.PI * 43;
  const strokeOffset = circumference - (percentage / 100) * circumference;

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.5, ease: "easeOut" }}
      className="relative mx-auto w-full max-w-3xl"
    >
      {/* Decorative background */}
      <div className="pointer-events-none absolute inset-x-0 -top-4 -z-10 overflow-hidden">
        <div className="absolute left-1/2 top-0 h-32 w-32 -translate-x-1/2 rounded-full bg-teal-100/40 blur-3xl sm:h-40 sm:w-40" />
      </div>

      {/* Header */}
      <motion.div
        initial={{ opacity: 0, y: 15 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.1, duration: 0.4 }}
        className="mb-6 text-center sm:mb-8"
      >
        <motion.div
          initial={{ scale: 0, rotate: -15 }}
          animate={{ scale: 1, rotate: 0 }}
          transition={{
            delay: 0.15,
            type: "spring",
            stiffness: 200,
            damping: 15,
          }}
          className="mx-auto mb-4 flex h-12 w-12 items-center justify-center rounded-2xl border border-teal-100 bg-teal-50 text-teal-600 shadow-sm shadow-teal-100 sm:mb-5 sm:h-16 sm:w-16"
        >
          <CheckCircle
            strokeWidth={1.8}
            className="h-6 w-6 sm:h-[30px] sm:w-[30px]"
          />
        </motion.div>

        <p className="text-[11px] font-bold uppercase tracking-[0.18em] text-teal-600 sm:text-xs sm:tracking-[0.2em]">
          Assessment complete
        </p>

        <h1 className="mt-2 text-xl font-bold leading-tight tracking-tight text-slate-900 sm:mt-3 sm:text-3xl lg:text-4xl">
          Your predicted wellness score
        </h1>

        <p className="mx-auto mt-2 max-w-md text-[12px] leading-5 text-slate-500 sm:mt-3 sm:max-w-lg sm:text-sm sm:leading-6">
          Your score is an estimate generated by our machine-learning model
          based on the information you provided.
        </p>
      </motion.div>

      {/* Main card */}
      <motion.div
        initial={{ opacity: 0, y: 20 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ delay: 0.2, duration: 0.4 }}
        className="overflow-hidden rounded-3xl border border-teal-500/30 bg-white shadow-xl shadow-slate-200/50 sm:rounded-[2rem]"
      >
        {/* Score section */}
        <div className="relative px-4 pb-6 pt-7 sm:px-8 sm:pb-8 sm:pt-10 lg:px-10">
          <div className="absolute left-1/2 top-0 h-1 w-20 -translate-x-1/2 rounded-full bg-teal-500 sm:w-24" />

          <div className="text-center">
            <p className="text-[11px] font-semibold uppercase tracking-[0.14em] text-slate-400 sm:text-xs sm:tracking-[0.16em]">
              Mental wellness score
            </p>

            {/* Circular score */}
            <div className="relative mx-auto mt-5 flex aspect-square w-44 items-center justify-center sm:mt-6 sm:w-56">
              <svg
                className="absolute inset-0 h-full w-full -rotate-90"
                viewBox="0 0 100 100"
              >
                <circle
                  cx="50"
                  cy="50"
                  r="47"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="1"
                  className="text-slate-100"
                />
                <circle
                  cx="50"
                  cy="50"
                  r="43"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="7"
                  className="text-slate-100"
                />
                <motion.circle
                  cx="50"
                  cy="50"
                  r="43"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth="7"
                  strokeLinecap="round"
                  className={result.progress}
                  strokeDasharray={circumference}
                  initial={{ strokeDashoffset: circumference }}
                  animate={{ strokeDashoffset: strokeOffset }}
                  transition={{ duration: 1.5, delay: 0.35, ease: "easeOut" }}
                />
              </svg>

              <div className="relative">
                <motion.div
                  initial={{ opacity: 0, scale: 0.7 }}
                  animate={{ opacity: 1, scale: 1 }}
                  transition={{ delay: 0.6, duration: 0.4 }}
                  className="text-4xl font-bold tracking-tight text-slate-900 sm:text-5xl"
                >
                  {score.toFixed(2)}
                </motion.div>

                <div className="mt-1 text-xs font-medium text-slate-400 sm:text-sm">
                  out of 10
                </div>
              </div>
            </div>

            {/* Result */}
            <motion.div
              initial={{ opacity: 0, y: 10 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: 0.8, duration: 0.4 }}
              className="mt-3"
            >
              <span
                className={`inline-flex items-center gap-2 rounded-full border px-3.5 py-1.5 text-xs font-semibold sm:px-4 sm:py-2 sm:text-sm ${result.badge}`}
              >
                <span className={`h-1.5 w-1.5 rounded-full ${result.dot}`} />
                {result.title}
              </span>

              <p className="mx-auto mt-3 max-w-md text-[12px] leading-5 text-slate-500 sm:mt-4 sm:text-sm sm:leading-6">
                {result.description}
              </p>
            </motion.div>
          </div>

          {/* Score scale */}
          <motion.div
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 1, duration: 0.4 }}
            className="mt-7 sm:mt-9"
          >
            <div className="mb-2 flex items-center justify-between text-xs md:text-sm font-medium text-slate-400">
              <span>0</span>
              <span>5</span>
              <span>10</span>
            </div>

            <div className="relative h-2 overflow-hidden rounded-full bg-slate-100 sm:h-2.5">
              <motion.div
                initial={{ width: 0 }}
                animate={{ width: `${percentage}%` }}
                transition={{ duration: 1.2, delay: 0.5, ease: "easeOut" }}
                className={`relative z-10 h-full rounded-full ${result.bar}`}
              />
            </div>

            <div className="mt-3 grid grid-cols-3 text-[12px] font-medium text-slate-400 sm:text-xs">
              <span className="text-left">Lower</span>
              <span className="text-center">Moderate</span>
              <span className="text-right">Higher</span>
            </div>
          </motion.div>

          {/* Suggestions */}
          <motion.div
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 1.1, duration: 0.4 }}
            className="mt-6 rounded-2xl border border-slate-200 bg-slate-50 p-4 sm:mt-8 sm:p-6"
          >
            <div className="flex items-center gap-2">
              <span className={`h-2 w-2 rounded-full ${result.dot}`} />
              <h3 className="text-sm sm:text-base font-semibold text-slate-800">
                What you can do
              </h3>
            </div>

            <ul className="mt-3 space-y-2.5 sm:mt-4 sm:space-y-3">
              {result.suggestions.map((suggestion) => (
                <li
                  key={suggestion}
                  className="flex items-start gap-2 sm:gap-3 text-[12px] leading-5 text-slate-500 sm:text-sm sm:leading-6"
                >
                  <span className="mt-[7px] h-1 w-1 shrink-0 rounded-full bg-slate-400 sm:mt-[9px]" />
                  <span>{suggestion}</span>
                </li>
              ))}
            </ul>
          </motion.div>
        </div>

        <div className="border-t border-slate-100" />

        {/* Disclaimer */}
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          transition={{ delay: 1.2, duration: 0.4 }}
          className="mx-4 mb-5 mt-5 flex items-start gap-3 rounded-2xl border border-slate-200 bg-slate-50 p-3.5 sm:mx-8 sm:mb-6 sm:p-4 lg:mx-10"
        >
          <ShieldCheck size={18} className="mt-0.5 shrink-0 text-red-400" />

          <p className="text-[12px] leading-5 text-slate-500 sm:text-sm">
            <strong className="font-semibold text-red-700">Important:</strong>{" "}
            This is a machine-learning prediction, not a medical diagnosis. If
            you are concerned about your mental health, consider speaking with a
            qualified healthcare professional.
          </p>
        </motion.div>

        {/* Restart */}
        <div className="px-4 pb-5 sm:px-8 sm:pb-8 lg:px-10 lg:pb-10">
          <motion.button
            type="button"
            onClick={onRestart}
            whileHover={{ scale: 1.01 }}
            whileTap={{ scale: 0.98 }}
            className="group flex w-full cursor-pointer items-center justify-center gap-2 rounded-2xl bg-slate-900 px-5 py-3.5 text-sm font-semibold text-white shadow-lg shadow-slate-900/10 transition hover:bg-slate-800 sm:py-4"
          >
            Take assessment again
            <RotateCcwClock
              size={18}
              className="transition-transform duration-300 group-hover:-rotate-45"
            />
          </motion.button>
        </div>
      </motion.div>

      <motion.p
        initial={{ opacity: 0 }}
        animate={{ opacity: 1 }}
        transition={{ delay: 1.35, duration: 0.4 }}
        className="mt-4 px-2 text-center text-[12px] text-slate-400 sm:mt-5 sm:text-sm"
      >
        Your result is based only on the information provided in this
        assessment.
      </motion.p>
    </motion.div>
  );
}
